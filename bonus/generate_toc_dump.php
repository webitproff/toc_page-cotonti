## 9. Проверка результата

После импорта зайдите в phpMyAdmin и проверьте таблицы:

- `cot_toc_page_trees` — одна запись с вашим деревом.
- `cot_toc_page_items` — строк столько же, сколько пунктов в вашем HTML. Поля:
  - `parent_id` = 0 для верхнего уровня,
  - `parent_id` = ID родителя для вложенных,
  - `item_sort` — порядок внутри одного родителя.
- `cot_toc_page_i18n` — если заполняли переводы, то для каждого элемента по одной строке с `lang = 'ru'`.

Также проверьте в админке Cotonti: раздел «Другое» → «Table of Contents Page». Выберите вкладку «Деревья» — должно появиться ваше дерево.

