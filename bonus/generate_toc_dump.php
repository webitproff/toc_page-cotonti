libxml_clear_errors();

$xpath = new DOMXPath($dom);
$topLevelUls = $xpath->query('//ul');

if ($topLevelUls->length === 0) {
    die('Не найден корневой <ul>');
}

$rootUl = $topLevelUls->item(0);

$items = [];
$nextId = 1;
$parentStack = [0];

function processUl(DOMElement $ul, array &$items, array &$parentStack, int &$nextId): void
{
    foreach ($ul->childNodes as $li) {
        if ($li->nodeName !== 'li') continue;

        // Извлекаем текст <li>, игнорируя <nav> и вложенные <ul>
        $title = '';
        foreach ($li->childNodes as $child) {
            if ($child->nodeName === 'nav') continue;
            if ($child->nodeName === 'ul') continue; // ← главное исправление
            if ($child->nodeType === XML_TEXT_NODE || $child->nodeType === XML_CDATA_SECTION_NODE) {
                $title .= $child->nodeValue;
            } elseif ($child->nodeType === XML_ELEMENT_NODE) {
                // Для вложенных элементов, кроме ul, берём их текст
                $title .= $child->textContent;
            }
        }
        $title = trim(preg_replace('/\s+/u', ' ', $title));
        if ($title === '') continue;

        $parentId = end($parentStack);
        $items[] = [$nextId, $parentId, $title];
        $currentId = $nextId;
        $nextId++;

        $childUl = null;
        foreach ($li->childNodes as $child) {
            if ($child->nodeName === 'ul') {
                $childUl = $child;
                break;
            }
        }

        if ($childUl !== null) {
            $parentStack[] = $currentId;
            processUl($childUl, $items, $parentStack, $nextId);
            array_pop($parentStack);
        }
    }
}

processUl($rootUl, $items, $parentStack, $nextId);

