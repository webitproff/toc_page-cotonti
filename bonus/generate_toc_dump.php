## 2. Подготовка HTML-списка

Откройте файл `generate_toc_dump.php` в любом текстовом редакторе (рекомендую Notepad++ или VS Code). Найдите секцию:

```php
$html = <<<'HTML'
...
HTML;
```

Между `<<<'HTML'` и `HTML;` должен находиться **только ваш HTML-список**. Ничего больше.

### 2.1. Правила построения списка

1. **Каждый пункт меню** — это тег `<li> ... </li>`.
2. **Родительский пункт** содержит вложенный `<ul>` **внутри своего `<li>`**.
3. **`<nav></nav>`** внутри `<li>` — **не обязателен**. Он полностью игнорируется скриптом и служит лишь для удобства (например, как метка). Вы можете вообще не писать его.
4. Внутри `<li>` можно использовать HTML-сущности (`&laquo;`, `&raquo;`, `&ndash;`, `&mdash;`). Они будут автоматически преобразованы в обычные символы.
5. **Не оставляйте лишних пробелов или переносов строк** между закрывающим `</li>` и следующим `<li>`. Они могут попасть в заголовок.
6. **Проверяйте вложенность**: открывающий `<ul>` должен быть строго внутри родительского `<li>`, а не после него.

#### Пример правильной структуры

```html
<ul>
    <li>Родительский пункт
        <ul>
            <li>Дочерний пункт 1</li>
            <li>Дочерний пункт 2
                <ul>
                    <li>Внук 1</li>
                    <li>Внук 2</li>
                </ul>
            </li>
        </ul>
    </li>
    <li>Ещё один родитель</li>
</ul>
```

#### Пример с `<nav></nav>` (не обязательно, но допустимо)

```html
<ul>
    <li><nav></nav>Родительский пункт
        <ul>
            <li>Дочерний пункт 1</li>
            <li>Дочерний пункт 2</li>
        </ul>
    </li>
</ul>
```

