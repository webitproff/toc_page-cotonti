# 📘 руководство по использованию `generate_toc_dump.php`

Этот файл создаёт SQL-дамп для плагина **Table of Contents Page (toc_page)** на основе вашего HTML-списка. После импорта дампа вы получите готовое дерево меню с переводами (если указаны).

> ⚠️ **Крайне важно!**  
> Скрипт при импорте **УДАЛЯЕТ существующие таблицы** `cot_toc_page_*` из базы данных и создаёт их заново. Если у вас уже есть деревья в плагине, они будут **безвозвратно потеряны**.  
> Перед импортом обязательно сделайте резервную копию базы данных или хотя бы этих трёх таблиц.

