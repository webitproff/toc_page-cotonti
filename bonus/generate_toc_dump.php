## 4. Настройка параметров дерева

Найдите:

```php
$treeId = 1;
$treeTitle = 'Prom.ua База знань';
$treeDescription = 'База знань Prom.ua для продавців';
```

- `$treeId` — уникальный числовой ID дерева. Если в базе уже есть дерево с ID 1, выберите свободный (например, 2, 3).  
  **Как узнать занятые ID:** посмотрите таблицу `cot_toc_page_trees` в phpMyAdmin.
- `$treeTitle` — название дерева (будет отображаться в админке плагина).
- `$treeDescription` — описание (необязательно, можно оставить пустым `''`).

