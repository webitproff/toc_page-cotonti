## 3. Настройка переводов

Найдите секцию:

```php
$translations = [
    'Украинский заголовок' => 'Русский перевод',
    // ...
];
```

**Правила:**

- Ключ — точный украинский текст, **как он отображается в HTML после удаления HTML-сущностей**.  
  Например, если в HTML написано `&laquo;Національний кешбек&raquo;`, в массиве ключ должен быть `«Національний кешбек»` (с обычными кавычками-ёлочками).
- Значение — русский перевод.
- Если перевода для какого-то пункта нет, скрипт использует украинский оригинал.
- Если переводы вообще не нужны, оставьте массив пустым: `$translations = [];`. Тогда в i18n будут записаны те же украинские строки.

**Как заполнить массив:**

Скопируйте все украинские заголовки (каждый с новой строки) и вручную добавьте русский перевод. Это долго, но необходимо для качественного результата.

