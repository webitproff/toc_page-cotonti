## 11. Возможные проблемы и их решение

| Симптом | Причина | Решение |
|---------|---------|---------|
| Сообщение `Не найден корневой <ul>` | В HTML нет ни одного `<ul>` или он не закрыт | Проверьте HTML |
| Ошибка `Ошибка записи файла` | Нет прав на запись в директории | Установите права 755 или 775 на корневую папку через FileZilla (правый клик → «Права доступа») |
| После импорта таблицы пустые | Не совпадает префикс таблиц | Замените `cot_` в скрипте на ваш префикс |
| Кириллица отображается как `?` | Файл скрипта не в UTF-8 | Сохраните файл в кодировке UTF-8 без BOM |
| В заголовках появились лишние слова | В HTML нарушена вложенность или есть пробелы между `</li>` и `<li>` | Проверьте HTML, уберите лишние пробелы |
| Не отображаются переводы | В массиве `$translations` ключ не совпадает с фактическим заголовком | Сверьте заголовки после парсинга (можно временно вывести `print_r($items)` перед генерацией SQL) |

