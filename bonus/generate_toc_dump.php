## 5. Префикс таблиц

В скрипте **жёстко прописан префикс `cot_`**. Если в вашей базе используется другой префикс, **обязательно замените его**.

**Как узнать свой префикс:**

1. Откройте файл конфигурации Cotonti: `datas/config.php` на сервере (через FileZilla).
2. Найдите строку вида:
   ```php
   $cfg['mysqlprefix'] = 'cot_';
   ```
   или
   ```php
   $db_x = 'cot_';
   ```
   Это и есть ваш префикс.
3. Если вы не можете открыть файл, зайдите в phpMyAdmin и посмотрите названия таблиц: например, `cot_users`, `cot_pages`. Часть до первого `_` — префикс.

**Замените в скрипте все вхождения `cot_` на ваш префикс.**  
Например, если префикс `cot_`, замените `cot_` на `cot_`.

