## 1. Что делает скрипт

- Принимает HTML-список (вложенные `<ul><li>`).
- Преобразует его в структуру таблиц плагина:
  - `toc_page_trees` — информация о дереве (1 запись).
  - `toc_page_items` — пункты меню с указанием `parent_id` и порядка сортировки.
  - `toc_page_i18n` — переводы заголовков на русский язык (если вы заполнили массив).
- Генерирует файл `.sql`, который вы затем импортируете в базу данных.

